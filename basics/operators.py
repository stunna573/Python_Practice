"""Arithmetic, comparison, and logical operator examples."""

first = 12
second = 5

print("Addition:", first + second)
print("Subtraction:", first - second)
print("Multiplication:", first * second)
print("Division:", first / second)
print("Floor division:", first // second)
print("Remainder:", first % second)
print("Power:", first ** second)

print("first is greater:", first > second)
print("Both conditions are true:", first > 10 and second < 10)
